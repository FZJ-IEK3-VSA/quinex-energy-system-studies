import os
import re
import json
import requests
import pandas as pd

class QuinexDiscussion():
    """
    Prepares the Discusssion Data from the results observed using quinex.
    """
    
    def __init__(self):
        """
        Initializes the discussion client.
        """

        pd.set_option('display.max_colwidth', None)

        with open("../data/visualisation_files/regex/entity_patterns.json", "r", encoding="utf-8") as f:
            self.entity_regex_map = json.load(f)
        self.entity_regex_map = {
            category: {
                label: [re.compile(p, re.IGNORECASE) for p in patterns]
                for label, patterns in labels.items()
            }
            for category, labels in self.entity_regex_map.items()
        }

        with open("../data/visualisation_files/regex/property_patterns.json", "r", encoding="utf-8") as f:
            self.property_regex_map = json.load(f)
        self.property_regex_map = {
            category: {
                label: [re.compile(p, re.IGNORECASE) for p in patterns]
                for label, patterns in labels.items()
            }
            for category, labels in self.property_regex_map.items()
        }

    # ----------------------------------- Functions for Loading and Saving Data -----------------------------------------------------------

    def load_df(self, path="df_quinex.parquet"):
        """
        Loads the DataFrame from disk.

        Args:
            path (str): File path of the saved DataFrame.
        """
        if not os.path.exists(path):
            raise FileNotFoundError(f"No saved DataFrame found at '{path}'")

        df = pd.read_parquet(path)
        print(f"📂 Loaded DataFrame from '{path}' with {len(df)} rows")
        return df
    

    def save_df(self, df: pd.DataFrame, path="df_quinex.parquet"):
        """
        Saves the DataFrame to disk.

        Args:
            df (pd.DataFrame): The DataFrame to save.
            path (str): File path to save the DataFrame.
        """
        df.to_parquet(path)
        print(f"💾 Saved DataFrame to '{path}' with {len(df)} rows")

    # ----------------------------------- Functions for Performing Regex Search -----------------------------------------------------------

    def map_entity(self, entity, regex_map):
        """
        Maps a given entity string to a category or subtype based on a regex mapping.

        Steps:
        1) Collect all possible matches for the entity.
        2) Special rule: if the category "hybrid" is present, it is always selected.
        3) Check for multiple categories. If more than one category matches, None is returned.
        4) Prefer subtype over base type if only one category matches.

        Args:
            entity (str | None): The entity string to classify.
            regex_map (dict): Dictionary in the format {category: {label: [re.Pattern, ...]}}.
        """
        if entity is None:
            return None

        entity_low = entity.lower()

        # 1) Collect all matches
        matches = []

        for category, items in regex_map.items():
            for label, patterns in items.items():
                for pat in patterns:
                    if pat.search(entity_low):
                        matches.append((category, label))

        # No matches → None
        if not matches:
            return None

        # 2) Special rule: "hybrid" has highest priority
        hybrid_hits = [label for cat,label in matches if cat == "hybrid"]
        if hybrid_hits:
            return hybrid_hits[0]

        # 3) Check for multiple categories
        categories = set([cat for cat,label in matches])
        if len(categories) > 1:
            return None

        # Only 1 category → prefer subtype over base type
        labels = [label for cat, label in matches if label.lower() != cat.lower()]
        if len(labels) > 1:
            # Multiple subtypes within the same category → None
            return None
        
        if labels:
            return labels[0]

        return [label for cat, label in matches if label.lower() == cat.lower()][0]


    def create_label_to_base(self, regex_map):
        """
    Creates a lookup dictionary from subtype labels to their base categories.

        Args:
            regex_map (dict): Dictionary in the format {base_category: {label: [re.Pattern, ...]}}.
        """

        label_to_base = {}
        for base_category, patterns in regex_map.items():
            for label in patterns.keys():
                label_to_base[label] = base_category
        return label_to_base


    def map_base_from_mapping(self, entity_mapping, label_to_base):
        """
        Maps a given entity label to its base category.

            Args:
                entity_mapping (str | None): The label previously assigned by `map_entity`.
                label_to_base (dict): Dictionary {label: base_category} generated by `create_label_to_base`.
        """

        if entity_mapping is None:
            return None
        return label_to_base.get(entity_mapping, None)
    

    # ----------------------------------- Functions for Helping the Layout -----------------------------------------------------------

    def print_df_sizes(self, df: pd.DataFrame):
        """
        Function to print the size of the Number Of Statements, Entities and Properties.

        Args:
            df (pd.DataFrame): The DataFrame for which to print the sizes.
        """

        print("Total Statements:", len(df))
        print("Number of Entities:", len(df["entity"].value_counts()))
        print("Number of Properties:", len(df["property"].value_counts()))